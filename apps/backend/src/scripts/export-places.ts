import { ExecArgs } from "@medusajs/framework/types"
import { ContainerRegistrationKeys } from "@medusajs/framework/utils"
import fs from "fs"
import path from "path"
import { PLACE_INDEX_MODULE } from "../modules/place-index"
import type { OsmPlace } from "../lib/osm-places"

type Row = OsmPlace & { id: string }
type Service = { listPlaces: (filters: object, config?: object) => Promise<Row[]> }

const HEADER = `import type { OsmPlace } from "../lib/osm-places"

/**
 * A snapshot of Qatar's places from OpenStreetMap, committed on purpose.
 *
 * The free Overpass servers this comes from are unavailable or rate limiting a
 * good share of the time, so a deploy cannot depend on reaching them: without
 * this file a fresh production database has an empty search box until a weekly
 * job happens to succeed. The import loads this first and layers live results
 * on top, so Overpass improves the index rather than gating it.
 *
 * A TypeScript module rather than JSON because \`medusa build\` compiles
 * TypeScript and does not copy data files — as JSON this is simply absent in
 * production. (Checked, not assumed.)
 *
 * Generated by \`npx medusa exec ./src/scripts/export-places.ts\`, never edited
 * by hand. Data © OpenStreetMap contributors, ODbL.
 */
export const QATAR_PLACES: OsmPlace[] = `

/**
 * Writes the database's place index back out as the committed snapshot.
 *
 *   npx medusa exec ./src/scripts/export-places.ts
 *
 * The pair to import-places: that one fills the database from Overpass, this
 * one freezes the result into the repo so the next fresh deploy starts with a
 * full search box instead of an empty one.
 *
 * Kept as a script rather than a hand-rolled parser over the .ts file because
 * the database is the thing that is actually correct — it has had every
 * successful weekly refresh applied to it, and the file has not.
 */
export default async function exportPlaces({ container }: ExecArgs) {
  const logger = container.resolve(ContainerRegistrationKeys.LOGGER)
  const service = container.resolve(PLACE_INDEX_MODULE) as Service

  const rows = await service.listPlaces({}, { take: 200000 })

  if (!rows.length) {
    logger.warn("places: the index is empty — refusing to overwrite the snapshot with nothing")
    return
  }

  // Sorted by kind then name so a regenerated file diffs against the last one
  // instead of reshuffling every line.
  const places: OsmPlace[] = rows
    .map((r) => ({
      osm_type: r.osm_type,
      osm_id: r.osm_id,
      name_en: r.name_en,
      name_ar: r.name_ar,
      kind: r.kind,
      context: r.context,
      // Six decimals is about 10 cm. Full float precision would make every
      // weekly refresh rewrite the whole file over differences no map shows.
      lat: round(r.lat),
      lng: round(r.lng),
    }))
    .sort((a, b) => a.kind.localeCompare(b.kind) || a.name_en.localeCompare(b.name_en))

  const target = path.join(process.cwd(), "src", "data", "qatar-places.ts")
  fs.writeFileSync(target, HEADER + JSON.stringify(places, null, 2) + "\n", "utf8")

  const byKind = new Map<string, number>()
  for (const p of places) byKind.set(p.kind, (byKind.get(p.kind) ?? 0) + 1)
  const summary = [...byKind.entries()].sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k} ${n}`)

  logger.info(`places: wrote ${places.length} to ${target}`)
  logger.info(`places: ${summary.join(", ")}`)
}

function round(value: number): number {
  return Math.round(value * 1e6) / 1e6
}
